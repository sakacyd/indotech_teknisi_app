import 'package:indotech_teknisi_app/features/report/domain/entities/installation_report.dart';

class InstallationReportModel extends InstallationReport {
  InstallationReportModel({
    required super.id,
    required super.reportId,
    required super.nomorSeriTangki,
    required super.nomorSeriKolektor,
    required super.pemasangan,
    required super.tangki,
    required super.collector,
    required super.elementHeating,
    required super.thermostat,
    required super.safetyValve,
    required super.kabelListrik,
    required super.pipa,
    required super.dinabolt,
    super.alasan,
    required super.tanggal,
    required super.materialDari,
    required super.instalasiOleh,
    super.note,
    required super.ttdTeknisi,
    required super.ttdCustomer,
  });

  factory InstallationReportModel.fromJson(Map<String, dynamic> json) {
    return InstallationReportModel(
      id: json['id'] as String,
      reportId: json['report_id'] as int,
      nomorSeriTangki: json['nomor_seri_tangki'] as String,
      nomorSeriKolektor: json['nomor_seri_kolektor'] as String,
      pemasangan: json['pemasangan'] as String,
      tangki: json['tangki'] as String,
      collector: json['collector'] as String,
      elementHeating: json['element_heating'] as String,
      thermostat: json['thermostat'] as String,
      safetyValve: json['safety_valve'] as String,
      kabelListrik: json['kabel_listrik'] as String,
      pipa: json['pipa'] as String,
      dinabolt: json['dinabolt'] as String,
      alasan: json['alasan'] as String?,
      tanggal: DateTime.parse(json['tanggal']),
      materialDari: json['material_dari'] as String,
      instalasiOleh: json['instalasi_oleh'] as String,
      note: json['note'] as String?,
      ttdTeknisi: json['ttd_teknisi'] as String,
      ttdCustomer: json['ttd_customer'] as String,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'report_id': reportId,
      'nomor_seri_tangki': nomorSeriTangki,
      'nomor_seri_kolektor': nomorSeriKolektor,
      'pemasangan': pemasangan,
      'tangki': tangki,
      'collector': collector,
      'element_heating': elementHeating,
      'thermostat': thermostat,
      'safety_valve': safetyValve,
      'kabel_listrik': kabelListrik,
      'pipa': pipa,
      'dinabolt': dinabolt,
      'alasan': alasan,
      'tanggal': tanggal.toIso8601String(),
      'material_dari': materialDari,
      'instalasi_oleh': instalasiOleh,
      'note': note,
      'ttd_teknisi': ttdTeknisi,
      'ttd_customer': ttdCustomer,
    };
  }

  InstallationReportModel copyWith({
    String? id,
    int? reportId,
    String? nomorSeriTangki,
    String? nomorSeriKolektor,
    String? pemasangan,
    String? tangki,
    String? collector,
    String? elementHeating,
    String? thermostat,
    String? safetyValve,
    String? kabelListrik,
    String? pipa,
    String? dinabolt,
    String? alasan,
    DateTime? tanggal,
    String? materialDari,
    String? instalasiOleh,
    String? note,
    String? ttdTeknisi,
    String? ttdCustomer,
  }) {
    return InstallationReportModel(
      id: id ?? this.id,
      reportId: reportId ?? this.reportId,
      nomorSeriTangki: nomorSeriTangki ?? this.nomorSeriTangki,
      nomorSeriKolektor: nomorSeriKolektor ?? this.nomorSeriKolektor,
      pemasangan: pemasangan ?? this.pemasangan,
      tangki: tangki ?? this.tangki,
      collector: collector ?? this.collector,
      elementHeating: elementHeating ?? this.elementHeating,
      thermostat: thermostat ?? this.thermostat,
      safetyValve: safetyValve ?? this.safetyValve,
      kabelListrik: kabelListrik ?? this.kabelListrik,
      pipa: pipa ?? this.pipa,
      dinabolt: dinabolt ?? this.dinabolt,
      alasan: alasan ?? this.alasan,
      tanggal: tanggal ?? this.tanggal,
      materialDari: materialDari ?? this.materialDari,
      instalasiOleh: instalasiOleh ?? this.instalasiOleh,
      note: note ?? this.note,
      ttdTeknisi: ttdTeknisi ?? this.ttdTeknisi,
      ttdCustomer: ttdCustomer ?? this.ttdCustomer,
    );
  }
}
