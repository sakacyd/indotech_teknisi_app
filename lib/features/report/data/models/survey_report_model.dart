import 'package:indotech_teknisi_app/features/report/domain/entities/survey_report.dart';

class SurveyReportModel extends SurveyReport {
  SurveyReportModel({
    required super.id,
    required super.reportId,
    required super.installationLocation,
    required super.roofFrameType,
    required super.needsReinforcement,
    required super.installationDirection,
    required super.obstructedByShade,
    required super.coldWaterLine,
    required super.hotWaterLine,
    required super.waterLineProvider,
    required super.estimatedWaterLineInstallation,
    required super.electricalCableLine,
    required super.cableLineProvider,
    required super.estimatedCableLineInstallation,
    required super.voltage,
    required super.amperage,
    required super.hertz,
    required super.watt,
    required super.coldWaterSource,
    required super.waterFromReservoir,
    required super.boosterPump,
    required super.pressureBar,
    super.poolVolume,
    super.poolLength,
    super.poolWidth,
    super.poolHeight,
    super.initialTemperature,
    super.targetTemperature,
    required super.visitDate,
    super.note,
    required super.imageUrl,
    required super.surveyorSignatureUrl,
    required super.customerSignatureUrl,
  });

  factory SurveyReportModel.fromJson(Map<String, dynamic> json) {
    return SurveyReportModel(
      id: json['id'] as String,
      reportId: json['report_id'] as int,
      installationLocation: json['installation_location'] as String,
      roofFrameType: json['roof_frame_type'] as String,
      needsReinforcement: json['needs_reinforcement'] as String,
      installationDirection: json['installation_direction'] as String,
      obstructedByShade: json['obstructed_by_shade'] as String,
      coldWaterLine: json['cold_water_line'] as String,
      hotWaterLine: json['hot_water_line'] as String,
      waterLineProvider: json['water_line_provider'] as String,
      estimatedWaterLineInstallation:
          json['estimated_water_line_installation'] as String,
      electricalCableLine: json['electrical_cable_line'] as String,
      cableLineProvider: json['cable_line_provider'] as String,
      estimatedCableLineInstallation:
          json['estimated_cable_line_installation'] as String,
      voltage: json['voltage'] as String,
      amperage: json['amperage'] as String,
      hertz: json['hertz'] as String,
      watt: json['watt'] as String,
      coldWaterSource: json['cold_water_source'] as String,
      waterFromReservoir: json['water_from_reservoir'] as String,
      boosterPump: json['booster_pump'] as String,
      pressureBar: json['pressure_bar'] as String,
      poolVolume: json['pool_volume'] as String?,
      poolLength: json['pool_length'] as String?,
      poolWidth: json['pool_width'] as String?,
      poolHeight: json['pool_height'] as String?,
      initialTemperature: json['initial_temperature'] as String?,
      targetTemperature: json['target_temperature'] as String?,
      visitDate: DateTime.parse(json['visit_date']),
      note: json['note'] as String?,
      imageUrl: json['image_url'] as String,
      surveyorSignatureUrl: json['surveyor_signature_url'] as String,
      customerSignatureUrl: json['customer_signature_url'] as String,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'report_id': reportId,
      'installation_location': installationLocation,
      'roof_frame_type': roofFrameType,
      'needs_reinforcement': needsReinforcement,
      'installation_direction': installationDirection,
      'obstructed_by_shade': obstructedByShade,
      'cold_water_line': coldWaterLine,
      'hot_water_line': hotWaterLine,
      'water_line_provider': waterLineProvider,
      'estimated_water_line_installation': estimatedWaterLineInstallation,
      'electrical_cable_line': electricalCableLine,
      'cable_line_provider': cableLineProvider,
      'estimated_cable_line_installation': estimatedCableLineInstallation,
      'voltage': voltage,
      'amperage': amperage,
      'hertz': hertz,
      'watt': watt,
      'cold_water_source': coldWaterSource,
      'water_from_reservoir': waterFromReservoir,
      'booster_pump': boosterPump,
      'pressure_bar': pressureBar,
      'pool_volume': poolVolume,
      'pool_length': poolLength,
      'pool_width': poolWidth,
      'pool_height': poolHeight,
      'initial_temperature': initialTemperature,
      'target_temperature': targetTemperature,
      'visit_date': visitDate.toIso8601String(),
      'note': note,
      'image_url': imageUrl,
      'surveyor_signature_url': surveyorSignatureUrl,
      'customer_signature_url': customerSignatureUrl,
    };
  }

  SurveyReportModel copyWith({
    String? id,
    int? reportId,
    String? installationLocation,
    String? roofFrameType,
    String? needsReinforcement,
    String? installationDirection,
    String? obstructedByShade,
    String? coldWaterLine,
    String? hotWaterLine,
    String? waterLineProvider,
    String? estimatedWaterLineInstallation,
    String? electricalCableLine,
    String? cableLineProvider,
    String? estimatedCableLineInstallation,
    String? voltage,
    String? amperage,
    String? hertz,
    String? watt,
    String? coldWaterSource,
    String? waterFromReservoir,
    String? boosterPump,
    String? pressureBar,
    String? poolVolume,
    String? poolLength,
    String? poolWidth,
    String? poolHeight,
    String? initialTemperature,
    String? targetTemperature,
    DateTime? visitDate,
    String? note,
    String? imageUrl,
    String? surveyorSignatureUrl,
    String? customerSignatureUrl,
  }) {
    return SurveyReportModel(
      id: id ?? this.id,
      reportId: reportId ?? this.reportId,
      installationLocation: installationLocation ?? this.installationLocation,
      roofFrameType: roofFrameType ?? this.roofFrameType,
      needsReinforcement: needsReinforcement ?? this.needsReinforcement,
      installationDirection:
          installationDirection ?? this.installationDirection,
      obstructedByShade: obstructedByShade ?? this.obstructedByShade,
      coldWaterLine: coldWaterLine ?? this.coldWaterLine,
      hotWaterLine: hotWaterLine ?? this.hotWaterLine,
      waterLineProvider: waterLineProvider ?? this.waterLineProvider,
      estimatedWaterLineInstallation:
          estimatedWaterLineInstallation ?? this.estimatedWaterLineInstallation,
      electricalCableLine: electricalCableLine ?? this.electricalCableLine,
      cableLineProvider: cableLineProvider ?? this.cableLineProvider,
      estimatedCableLineInstallation:
          estimatedCableLineInstallation ?? this.estimatedCableLineInstallation,
      voltage: voltage ?? this.voltage,
      amperage: amperage ?? this.amperage,
      hertz: hertz ?? this.hertz,
      watt: watt ?? this.watt,
      coldWaterSource: coldWaterSource ?? this.coldWaterSource,
      waterFromReservoir: waterFromReservoir ?? this.waterFromReservoir,
      boosterPump: boosterPump ?? this.boosterPump,
      pressureBar: pressureBar ?? this.pressureBar,
      poolVolume: poolVolume ?? this.poolVolume,
      poolLength: poolLength ?? this.poolLength,
      poolWidth: poolWidth ?? this.poolWidth,
      poolHeight: poolHeight ?? this.poolHeight,
      initialTemperature: initialTemperature ?? this.initialTemperature,
      targetTemperature: targetTemperature ?? this.targetTemperature,
      visitDate: visitDate ?? this.visitDate,
      note: note ?? this.note,
      imageUrl: imageUrl ?? this.imageUrl,
      surveyorSignatureUrl: surveyorSignatureUrl ?? this.surveyorSignatureUrl,
      customerSignatureUrl: customerSignatureUrl ?? this.customerSignatureUrl,
    );
  }
}
