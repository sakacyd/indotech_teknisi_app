class User {
  final String id;
  final String name;
  final String email;
  final String imageUrl;
  final String phoneNumber;
  final String address;
  final String bloodType;

  User({
    required this.id,
    required this.name,
    required this.email,
    required this.imageUrl,
    required this.phoneNumber,
    required this.address,
    required this.bloodType,
  });
}
